create trigger vendor_accounts_availability_event_v1
after insert or update of accepting_orders on public.vendor_accounts
for each row execute function public.record_vendor_availability_event_v1();

insert into public.vendor_availability_events (
  vendor_id,
  accepting_orders,
  changed_at,
  source
)
