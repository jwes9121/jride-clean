create or replace function public.record_vendor_availability_event_v1()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if tg_op = 'INSERT' or new.accepting_orders is distinct from old.accepting_orders then
    insert into public.vendor_availability_events (
      vendor_id,
      accepting_orders,
      changed_at,
      source
    ) values (
      new.id,
      new.accepting_orders,
      now(),
      'vendor_accounts_trigger'
    );
  end if;
  return new;
end;
$$;

