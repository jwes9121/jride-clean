create or replace function public.capture_takeout_vendor_response_times_v1()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  old_status text := lower(trim(coalesce(old.vendor_status, '')));
  new_status text := lower(trim(coalesce(new.vendor_status, '')));
  response_reason text := lower(trim(coalesce(new.vendor_cancel_reason, new.cancel_reason, '')));
  response_time timestamptz := now();
begin
  if lower(trim(coalesce(new.service_type, ''))) <> 'takeout' then
    return new;
  end if;

  if (
    new_status = 'vendor_timeout'
    or response_reason like '%did not respond within%'
    or response_reason like '%vendor timeout%'
  ) then
    new.vendor_timeout_at := coalesce(new.vendor_timeout_at, response_time);
    new.vendor_responded_at := coalesce(new.vendor_responded_at, new.vendor_timeout_at, response_time);
    return new;
  end if;

  if old_status in ('', 'requested', 'vendor_pending')
     and new_status in ('cancelled', 'canceled') then
    new.vendor_rejected_at := coalesce(new.vendor_rejected_at, response_time);
    new.vendor_responded_at := coalesce(new.vendor_responded_at, new.vendor_rejected_at, response_time);
    return new;
  end if;

  if new_status in (
    'vendor_accepted',
    'accepted',
    'driver_assigned',
    'driver_accepted',
    'preparing',
    'pickup_ready',
    'rider_arrived_vendor',
    'arrived_vendor',
    'picked_up',
    'delivering',
    'completed'
  ) then
    new.vendor_accepted_at := coalesce(new.vendor_accepted_at, response_time);
    new.vendor_responded_at := coalesce(new.vendor_responded_at, new.vendor_accepted_at, response_time);
  end if;

  return new;
end;
$$;

drop trigger if exists bookings_takeout_vendor_response_times_v1 on public.bookings;
create trigger bookings_takeout_vendor_response_times_v1
before update of vendor_status, vendor_cancel_reason, cancel_reason on public.bookings
for each row execute function public.capture_takeout_vendor_response_times_v1();

