begin;

create table if not exists public.booking_timestamp_repair_audit (
  id bigint generated by default as identity primary key,
  booking_id uuid not null references public.bookings(id) on delete cascade,
  booking_code text null,
  field_name text not null,
  original_value timestamptz null,
  repaired_value timestamptz null,
  repair_reason text not null,
  repaired_at timestamptz not null default now(),
  unique (booking_id, field_name, repair_reason)
);

alter table public.booking_timestamp_repair_audit enable row level security;

insert into public.booking_timestamp_repair_audit (
  booking_id,
  booking_code,
  field_name,
  original_value,
  repaired_value,
  repair_reason
)
select
  booking.id,
  booking.booking_code,
  'vendor_timeout_at',
  booking.vendor_timeout_at,
  null,
  'Cleared impossible historical timeout timestamp more than 30 minutes after order creation; exact event time was not captured'
from public.bookings booking
where lower(coalesce(booking.service_type, '')) = 'takeout'
  and lower(coalesce(booking.vendor_status, '')) = 'vendor_timeout'
  and booking.vendor_timeout_at is not null
  and booking.vendor_timeout_at > booking.created_at + interval '30 minutes'
  and booking.vendor_responded_at = booking.vendor_timeout_at
on conflict (booking_id, field_name, repair_reason) do nothing;

insert into public.booking_timestamp_repair_audit (
  booking_id,
  booking_code,
  field_name,
  original_value,
  repaired_value,
  repair_reason
)
select
  booking.id,
  booking.booking_code,
  'vendor_responded_at',
  booking.vendor_responded_at,
  null,
  'Cleared impossible historical timeout timestamp more than 30 minutes after order creation; exact event time was not captured'
from public.bookings booking
where lower(coalesce(booking.service_type, '')) = 'takeout'
  and lower(coalesce(booking.vendor_status, '')) = 'vendor_timeout'
  and booking.vendor_timeout_at is not null
  and booking.vendor_timeout_at > booking.created_at + interval '30 minutes'
  and booking.vendor_responded_at = booking.vendor_timeout_at
on conflict (booking_id, field_name, repair_reason) do nothing;

update public.bookings booking
set vendor_timeout_at = null,
    vendor_responded_at = null
where lower(coalesce(booking.service_type, '')) = 'takeout'
  and lower(coalesce(booking.vendor_status, '')) = 'vendor_timeout'
  and booking.vendor_timeout_at is not null
  and booking.vendor_timeout_at > booking.created_at + interval '30 minutes'
  and booking.vendor_responded_at = booking.vendor_timeout_at;

-- The legacy trigger stamped the current time onto old timeout rows when a
-- later maintenance update touched their status or reason. The transition-aware
-- trigger trg_capture_takeout_vendor_response_v1 remains authoritative.
drop trigger if exists bookings_takeout_vendor_response_times_v1 on public.bookings;

comment on table public.booking_timestamp_repair_audit is
  'Audit record of timestamp corrections. Original values are retained when an impossible historical timestamp is cleared.';

commit;
